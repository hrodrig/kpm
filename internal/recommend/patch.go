package recommend

import (
	"fmt"
	"math"
	"regexp"
	"strings"
	"time"

	"github.com/hrodrig/kpm/internal/store"
)

// PatchFormat selects export shape for GitOps copy/download (#18b).
type PatchFormat string

const (
	// PatchStrategic is a single strategic-merge style YAML fragment.
	PatchStrategic PatchFormat = "strategic"
	// PatchKustomize wraps the strategic patch with kustomization hints.
	PatchKustomize PatchFormat = "kustomize"
)

// PatchExport is a read-only artifact for operators (never applied by kpm).
type PatchExport struct {
	Format   PatchFormat
	Filename string
	Content  string
	GrainKey string
}

// dns1123Subdomain matches Kubernetes object / namespace names (DNS-1123 subdomain).
var dns1123Subdomain = regexp.MustCompile(`^[a-z0-9]([-a-z0-9]*[a-z0-9])?(\.[a-z0-9]([-a-z0-9]*[a-z0-9])?)*$`)

// dns1123Label matches container names (DNS-1123 label).
var dns1123Label = regexp.MustCompile(`^[a-z0-9]([-a-z0-9]*[a-z0-9])?$`)

// FormatResourcePatch builds a YAML patch from a recommendation snapshot.
// Only requests are set (suggested values). Limits are left untouched.
// The header stamp uses the local timezone (RFC3339 offset).
func FormatResourcePatch(rec store.Recommendation, format PatchFormat) (PatchExport, error) {
	return FormatResourcePatchAt(rec, format, time.Now())
}

// FormatResourcePatchAt is FormatResourcePatch with an explicit clock (tests / replay).
func FormatResourcePatchAt(rec store.Recommendation, format PatchFormat, at time.Time) (PatchExport, error) {
	if strings.TrimSpace(rec.GrainKey) == "" && strings.TrimSpace(rec.OwnerName) == "" && strings.TrimSpace(rec.Pod) == "" {
		return PatchExport{}, fmt.Errorf("recommendation missing identity")
	}
	if format == "" {
		format = PatchStrategic
	}
	switch format {
	case PatchStrategic, PatchKustomize:
	default:
		return PatchExport{}, fmt.Errorf("unknown patch format %q (want strategic|kustomize)", format)
	}

	kind, name, ns, container, err := patchTarget(rec)
	if err != nil {
		return PatchExport{}, err
	}
	if kind == "Deployment" && strings.TrimSpace(rec.OwnerKind) == "ReplicaSet" {
		name = stripReplicaSetHash(name)
	}
	cpu := CPUQuantity(rec.CPUSugMcores)
	mem := MemQuantity(rec.MemSugBytes)
	stamp := at.In(time.Local).Format(time.RFC3339)
	body := strategicMergeYAML(kind, name, ns, container, cpu, mem, stamp)

	out := PatchExport{
		Format:   format,
		GrainKey: rec.GrainKey,
		Filename: patchFilename(name, format),
		Content:  body,
	}
	if format == PatchKustomize {
		out.Content = kustomizeWrap(body, out.Filename)
		out.Filename = "kustomization-hint-" + sanitizeFile(name) + ".md"
	}
	return out, nil
}

func patchTarget(rec store.Recommendation) (kind, name, ns, container string, err error) {
	ns = strings.TrimSpace(rec.Namespace)
	container = strings.TrimSpace(rec.Container)
	if container == "" {
		container = "main"
	}
	rawKind := strings.TrimSpace(rec.OwnerKind)
	name = strings.TrimSpace(rec.OwnerName)
	if rawKind != "" && name != "" {
		mapped, ok := mapOwnerKind(rawKind)
		if !ok {
			return "", "", "", "", fmt.Errorf("unsupported owner kind %q", rawKind)
		}
		kind = mapped
	} else {
		kind = "Pod"
		name = strings.TrimSpace(rec.Pod)
	}
	if err := validateDNS1123Subdomain(name, "name"); err != nil {
		return "", "", "", "", err
	}
	if ns != "" {
		if err := validateDNS1123Subdomain(ns, "namespace"); err != nil {
			return "", "", "", "", err
		}
	}
	if err := validateDNS1123Label(container, "container"); err != nil {
		return "", "", "", "", err
	}
	return kind, name, ns, container, nil
}

func mapOwnerKind(kind string) (string, bool) {
	switch kind {
	case "ReplicaSet":
		// Pods usually show ReplicaSet; operators patch the Deployment.
		return "Deployment", true
	case "Deployment", "StatefulSet", "DaemonSet", "Job", "CronJob", "Pod":
		return kind, true
	default:
		return "", false
	}
}

func validateDNS1123Subdomain(s, field string) error {
	if len(s) == 0 || len(s) > 253 || !dns1123Subdomain.MatchString(s) {
		return fmt.Errorf("invalid %s %q (want DNS-1123 subdomain)", field, s)
	}
	return nil
}

func validateDNS1123Label(s, field string) error {
	if len(s) == 0 || len(s) > 63 || !dns1123Label.MatchString(s) {
		return fmt.Errorf("invalid %s %q (want DNS-1123 label)", field, s)
	}
	return nil
}

func patchAPIVersion(kind string) string {
	switch kind {
	case "Pod":
		return "v1"
	case "Job", "CronJob":
		return "batch/v1"
	default:
		return "apps/v1"
	}
}

func strategicMergeYAML(kind, name, ns, container, cpu, mem, stamp string) string {
	var b strings.Builder
	_, _ = fmt.Fprintf(&b, "# Generated by kpm at %s — GitOps copy/download only (do not kubectl apply from kpm).\n", stamp)
	_, _ = fmt.Fprintf(&b, "apiVersion: %s\n", patchAPIVersion(kind))
	_, _ = fmt.Fprintf(&b, "kind: %s\n", kind)
	_, _ = fmt.Fprintf(&b, "metadata:\n")
	_, _ = fmt.Fprintf(&b, "  name: %s\n", yamlQuote(name))
	if ns != "" {
		_, _ = fmt.Fprintf(&b, "  namespace: %s\n", yamlQuote(ns))
	}
	switch kind {
	case "Pod":
		writePodContainers(&b, container, cpu, mem)
	case "CronJob":
		_, _ = fmt.Fprintf(&b, "spec:\n")
		_, _ = fmt.Fprintf(&b, "  jobTemplate:\n")
		_, _ = fmt.Fprintf(&b, "    spec:\n")
		_, _ = fmt.Fprintf(&b, "      template:\n")
		_, _ = fmt.Fprintf(&b, "        spec:\n")
		writeNestedContainers(&b, "          ", container, cpu, mem)
	default:
		_, _ = fmt.Fprintf(&b, "spec:\n")
		_, _ = fmt.Fprintf(&b, "  template:\n")
		_, _ = fmt.Fprintf(&b, "    spec:\n")
		writeNestedContainers(&b, "      ", container, cpu, mem)
	}
	return b.String()
}

func writePodContainers(b *strings.Builder, container, cpu, mem string) {
	_, _ = fmt.Fprintf(b, "spec:\n")
	_, _ = fmt.Fprintf(b, "  containers:\n")
	_, _ = fmt.Fprintf(b, "  - name: %s\n", yamlQuote(container))
	_, _ = fmt.Fprintf(b, "    resources:\n")
	_, _ = fmt.Fprintf(b, "      requests:\n")
	_, _ = fmt.Fprintf(b, "        cpu: %s\n", yamlQuote(cpu))
	_, _ = fmt.Fprintf(b, "        memory: %s\n", yamlQuote(mem))
}

func writeNestedContainers(b *strings.Builder, indent, container, cpu, mem string) {
	_, _ = fmt.Fprintf(b, "%scontainers:\n", indent)
	_, _ = fmt.Fprintf(b, "%s- name: %s\n", indent, yamlQuote(container))
	_, _ = fmt.Fprintf(b, "%s  resources:\n", indent)
	_, _ = fmt.Fprintf(b, "%s    requests:\n", indent)
	_, _ = fmt.Fprintf(b, "%s      cpu: %s\n", indent, yamlQuote(cpu))
	_, _ = fmt.Fprintf(b, "%s      memory: %s\n", indent, yamlQuote(mem))
}

// stripReplicaSetHash drops a trailing pod-template-hash segment from an RS name
// so offline patches can target the parent Deployment when sample-time resolve
// was not available (historical rows).
func stripReplicaSetHash(name string) string {
	i := strings.LastIndex(name, "-")
	if i <= 0 {
		return name
	}
	hash := name[i+1:]
	if len(hash) < 5 || len(hash) > 10 {
		return name
	}
	for _, r := range hash {
		if (r < 'a' || r > 'z') && (r < '0' || r > '9') {
			return name
		}
	}
	return name[:i]
}

// yamlQuote returns a double-quoted YAML scalar (safe for validated identifiers).
func yamlQuote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\', '"':
			b.WriteByte('\\')
			b.WriteRune(r)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func kustomizeWrap(patchBody, patchFile string) string {
	base := strings.TrimSuffix(patchFile, ".yaml")
	if base == patchFile {
		base = "patch-resources"
	}
	var b strings.Builder
	_, _ = fmt.Fprintf(&b, "# kpm GitOps export — paste into an overlay (never applied by kpm).\n")
	_, _ = fmt.Fprintf(&b, "#\n")
	_, _ = fmt.Fprintf(&b, "# kustomization.yaml (sketch):\n")
	_, _ = fmt.Fprintf(&b, "#   apiVersion: kustomize.config.k8s.io/v1beta1\n")
	_, _ = fmt.Fprintf(&b, "#   kind: Kustomization\n")
	_, _ = fmt.Fprintf(&b, "#   resources:\n")
	_, _ = fmt.Fprintf(&b, "#     - ../../base\n")
	_, _ = fmt.Fprintf(&b, "#   patches:\n")
	_, _ = fmt.Fprintf(&b, "#     - path: %s.yaml\n", base)
	_, _ = fmt.Fprintf(&b, "#\n")
	_, _ = fmt.Fprintf(&b, "# --- %s.yaml ---\n", base)
	_, _ = b.WriteString(patchBody)
	return b.String()
}

func patchFilename(name string, format PatchFormat) string {
	base := "patch-" + sanitizeFile(name)
	if format == PatchKustomize {
		return base + ".yaml"
	}
	return base + ".yaml"
}

func sanitizeFile(s string) string {
	s = strings.TrimSpace(s)
	if s == "" {
		return "workload"
	}
	var b strings.Builder
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '-', r == '_':
			b.WriteRune(r)
		default:
			b.WriteByte('-')
		}
	}
	out := strings.Trim(b.String(), "-")
	if out == "" {
		return "workload"
	}
	return out
}

// CPUQuantity formats millicores as a Kubernetes CPU quantity (e.g. "100m").
func CPUQuantity(mcores float64) string {
	if mcores <= 0 {
		return "0"
	}
	return fmt.Sprintf("%dm", int64(math.Round(mcores)))
}

// MemQuantity formats bytes as a Kubernetes memory quantity (Mi preferred).
func MemQuantity(bytes int64) string {
	return formatBytes(bytes)
}
