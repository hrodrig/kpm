package recommend

import (
	"fmt"
	"math"
	"strings"
	"time"

	"github.com/hrodrig/kpm/internal/store"
)

// PatchFormat selects export shape for GitOps copy/download (#18b).
type PatchFormat string

const (
	// PatchStrategic is a single strategic-merge style YAML fragment.
	PatchStrategic PatchFormat = "strategic"
	// PatchKustomize wraps the strategic patch with kustomization hints.
	PatchKustomize PatchFormat = "kustomize"
)

// PatchExport is a read-only artifact for operators (never applied by kpm).
type PatchExport struct {
	Format   PatchFormat
	Filename string
	Content  string
	GrainKey string
}

// FormatResourcePatch builds a YAML patch from a recommendation snapshot.
// Only requests are set (suggested values). Limits are left untouched.
// The header stamp uses the local timezone (RFC3339 offset).
func FormatResourcePatch(rec store.Recommendation, format PatchFormat) (PatchExport, error) {
	return FormatResourcePatchAt(rec, format, time.Now())
}

// FormatResourcePatchAt is FormatResourcePatch with an explicit clock (tests / replay).
func FormatResourcePatchAt(rec store.Recommendation, format PatchFormat, at time.Time) (PatchExport, error) {
	if strings.TrimSpace(rec.GrainKey) == "" && strings.TrimSpace(rec.OwnerName) == "" && strings.TrimSpace(rec.Pod) == "" {
		return PatchExport{}, fmt.Errorf("recommendation missing identity")
	}
	if format == "" {
		format = PatchStrategic
	}
	switch format {
	case PatchStrategic, PatchKustomize:
	default:
		return PatchExport{}, fmt.Errorf("unknown patch format %q (want strategic|kustomize)", format)
	}

	kind, name, ns, container := patchTarget(rec)
	cpu := CPUQuantity(rec.CPUSugMcores)
	mem := MemQuantity(rec.MemSugBytes)
	stamp := at.In(time.Local).Format(time.RFC3339)
	body := strategicMergeYAML(kind, name, ns, container, cpu, mem, stamp)

	out := PatchExport{
		Format:   format,
		GrainKey: rec.GrainKey,
		Filename: patchFilename(name, format),
		Content:  body,
	}
	if format == PatchKustomize {
		out.Content = kustomizeWrap(body, out.Filename)
		out.Filename = "kustomization-hint-" + sanitizeFile(name) + ".md"
	}
	return out, nil
}

func patchTarget(rec store.Recommendation) (kind, name, ns, container string) {
	ns = strings.TrimSpace(rec.Namespace)
	container = strings.TrimSpace(rec.Container)
	if container == "" {
		container = "main"
	}
	kind = strings.TrimSpace(rec.OwnerKind)
	name = strings.TrimSpace(rec.OwnerName)
	if kind != "" && name != "" {
		return mapOwnerKind(kind), name, ns, container
	}
	// Pod-grain fallback.
	return "Pod", strings.TrimSpace(rec.Pod), ns, container
}

func mapOwnerKind(kind string) string {
	switch kind {
	case "ReplicaSet":
		// Pods usually show ReplicaSet; operators patch the Deployment.
		return "Deployment"
	default:
		return kind
	}
}

func strategicMergeYAML(kind, name, ns, container, cpu, mem, stamp string) string {
	api := "apps/v1"
	if kind == "Pod" {
		api = "v1"
	}
	var b strings.Builder
	_, _ = fmt.Fprintf(&b, "# Generated by kpm at %s — GitOps copy/download only (do not kubectl apply from kpm).\n", stamp)
	_, _ = fmt.Fprintf(&b, "apiVersion: %s\n", api)
	_, _ = fmt.Fprintf(&b, "kind: %s\n", kind)
	_, _ = fmt.Fprintf(&b, "metadata:\n")
	_, _ = fmt.Fprintf(&b, "  name: %s\n", name)
	if ns != "" {
		_, _ = fmt.Fprintf(&b, "  namespace: %s\n", ns)
	}
	if kind == "Pod" {
		_, _ = fmt.Fprintf(&b, "spec:\n")
		_, _ = fmt.Fprintf(&b, "  containers:\n")
		_, _ = fmt.Fprintf(&b, "  - name: %s\n", container)
		_, _ = fmt.Fprintf(&b, "    resources:\n")
		_, _ = fmt.Fprintf(&b, "      requests:\n")
		_, _ = fmt.Fprintf(&b, "        cpu: %q\n", cpu)
		_, _ = fmt.Fprintf(&b, "        memory: %q\n", mem)
		return b.String()
	}
	_, _ = fmt.Fprintf(&b, "spec:\n")
	_, _ = fmt.Fprintf(&b, "  template:\n")
	_, _ = fmt.Fprintf(&b, "    spec:\n")
	_, _ = fmt.Fprintf(&b, "      containers:\n")
	_, _ = fmt.Fprintf(&b, "      - name: %s\n", container)
	_, _ = fmt.Fprintf(&b, "        resources:\n")
	_, _ = fmt.Fprintf(&b, "          requests:\n")
	_, _ = fmt.Fprintf(&b, "            cpu: %q\n", cpu)
	_, _ = fmt.Fprintf(&b, "            memory: %q\n", mem)
	return b.String()
}

func kustomizeWrap(patchBody, patchFile string) string {
	base := strings.TrimSuffix(patchFile, ".yaml")
	if base == patchFile {
		base = "patch-resources"
	}
	var b strings.Builder
	_, _ = fmt.Fprintf(&b, "# kpm GitOps export — paste into an overlay (never applied by kpm).\n")
	_, _ = fmt.Fprintf(&b, "#\n")
	_, _ = fmt.Fprintf(&b, "# kustomization.yaml (sketch):\n")
	_, _ = fmt.Fprintf(&b, "#   apiVersion: kustomize.config.k8s.io/v1beta1\n")
	_, _ = fmt.Fprintf(&b, "#   kind: Kustomization\n")
	_, _ = fmt.Fprintf(&b, "#   resources:\n")
	_, _ = fmt.Fprintf(&b, "#     - ../../base\n")
	_, _ = fmt.Fprintf(&b, "#   patches:\n")
	_, _ = fmt.Fprintf(&b, "#     - path: %s.yaml\n", base)
	_, _ = fmt.Fprintf(&b, "#\n")
	_, _ = fmt.Fprintf(&b, "# --- %s.yaml ---\n", base)
	_, _ = b.WriteString(patchBody)
	return b.String()
}

func patchFilename(name string, format PatchFormat) string {
	base := "patch-" + sanitizeFile(name)
	if format == PatchKustomize {
		return base + ".yaml"
	}
	return base + ".yaml"
}

func sanitizeFile(s string) string {
	s = strings.TrimSpace(s)
	if s == "" {
		return "workload"
	}
	var b strings.Builder
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '-', r == '_':
			b.WriteRune(r)
		default:
			b.WriteByte('-')
		}
	}
	out := strings.Trim(b.String(), "-")
	if out == "" {
		return "workload"
	}
	return out
}

// CPUQuantity formats millicores as a Kubernetes CPU quantity (e.g. "100m").
func CPUQuantity(mcores float64) string {
	if mcores <= 0 {
		return "0"
	}
	return fmt.Sprintf("%dm", int64(math.Round(mcores)))
}

// MemQuantity formats bytes as a Kubernetes memory quantity (Mi preferred).
func MemQuantity(bytes int64) string {
	return formatBytes(bytes)
}
