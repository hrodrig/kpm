func TestFormatResourcePatchStrategic(t *testing.T) {
	rec := store.Recommendation{
		Grain: "workload", GrainKey: "Deployment/api/main",
		Namespace: "app", OwnerKind: "Deployment", OwnerName: "api", Container: "main",
		CPUSugMcores: 250, MemSugBytes: 128 * 1024 * 1024,
	}
	at := time.Date(2026, 10, 12, 6, 31, 0, 0, time.Local)
	out, err := recommend.FormatResourcePatchAt(rec, recommend.PatchStrategic, at)
	if err != nil {
		t.Fatal(err)
	}
	if out.Filename == "" || out.GrainKey != rec.GrainKey {
		t.Fatalf("%+v", out)
	}
	stampLine := "Generated by kpm at " + at.In(time.Local).Format(time.RFC3339)
	for _, want := range []string{
		"kind: Deployment",
		`name: "api"`,
		`namespace: "app"`,
		`name: "main"`,
		`cpu: "250m"`,
		`memory: "128Mi"`,
		"do not kubectl apply from kpm",
		stampLine,
	} {
		if !strings.Contains(out.Content, want) {
			t.Fatalf("missing %q in:\n%s", want, out.Content)
		}
	}
}

func TestFormatResourcePatchReplicaSetMapsDeployment(t *testing.T) {
	rec := store.Recommendation{
		Namespace: "app", OwnerKind: "ReplicaSet", OwnerName: "web-7d9f8c", Container: "c",
		CPUSugMcores: 100, MemSugBytes: 64 * 1024 * 1024,
	}
	out, err := recommend.FormatResourcePatch(rec, recommend.PatchKustomize)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out.Content, "kind: Deployment") {
		t.Fatalf("want Deployment mapping:\n%s", out.Content)
	}
	if !strings.Contains(out.Content, `name: "web"`) {
		t.Fatalf("want hash stripped to Deployment name:\n%s", out.Content)
	}
	if !strings.Contains(out.Content, "kustomization.yaml") {
		t.Fatalf("want kustomize hint:\n%s", out.Content)
	}
}

func TestFormatResourcePatchCronJobJobTemplate(t *testing.T) {
	rec := store.Recommendation{
		Namespace: "batch", OwnerKind: "CronJob", OwnerName: "nightly", Container: "job",
		CPUSugMcores: 50, MemSugBytes: 32 * 1024 * 1024,
	}
	out, err := recommend.FormatResourcePatch(rec, recommend.PatchStrategic)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"kind: CronJob",
		"apiVersion: batch/v1",
		"jobTemplate:",
		"containers:",
		`name: "job"`,
	} {
		if !strings.Contains(out.Content, want) {
			t.Fatalf("missing %q in:\n%s", want, out.Content)
		}
	}
	if strings.Contains(out.Content, "spec:\n  template:\n") {
		t.Fatalf("CronJob must not use Deployment-style template path:\n%s", out.Content)
	}
}

func TestFormatResourcePatchErrors(t *testing.T) {
	if _, err := recommend.FormatResourcePatch(store.Recommendation{}, recommend.PatchStrategic); err == nil {
		t.Fatal("want identity error")
	}
	rec := store.Recommendation{Pod: "p", Namespace: "ns", Container: "c", CPUSugMcores: 10}
	if _, err := recommend.FormatResourcePatch(rec, "nope"); err == nil {
		t.Fatal("want format error")
	}
	out, err := recommend.FormatResourcePatch(rec, recommend.PatchStrategic)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out.Content, "kind: Pod") {
		t.Fatalf("%s", out.Content)
	}
}

